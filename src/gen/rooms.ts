//
// 圖例：
//   #  牆            .  地板          o  石柱          =  矮牆（1.0 m）
//   P  高台（1.3 m） ^  尖刺踏板      s  補給點        C  寶箱
//   H  沉眠之心台座  X  出口階梯      @  出生點
//   R  補給台（練習） 1-9  敵人（見 enemies）          a-h  巡邏點
//   "  長草（擋視線）  ~  淺水           _  深坑          V  寶庫台座

export type Face = 'N' | 'S' | 'E' | 'W';
export type EnemyKind = 'guard' | 'archer' | 'charger' | 'warden' | 'rat' | 'bomber' | 'sentry' | 'mimic' | 'statue';
export type Role = 'entrance' | 'combat' | 'treasure' | 'heart' | 'shortcut' | 'practice';

export interface EnemyDef {
  m: string;
  kind: EnemyKind;
  state: 'sleep' | 'idle' | 'patrol';
  face: Face;
  /** 房間難度層級 ≥ tier 才會出現。 */
  tier: number;
  patrol?: string;
  perched?: boolean;
}

export interface RoomLayout {
  id: string;
  name: string;
  role: Role;
  rows: string[];
  enemies: EnemyDef[];
  spawnFace?: Face;
  /** 生成版本 2 才使用的版型（舊存檔的房間池不變）。 */
  v2?: true;
  /** 只當特殊房使用，不進一般房間池。 */
  special?: true;
}

