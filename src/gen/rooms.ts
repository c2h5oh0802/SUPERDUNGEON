export function layoutsByRole(role: Role): RoomLayout[] {
  return LAYOUTS.filter((l) => l.role === role && !l.v2 && !['ember-cache', 'sentry-vault', 'guardian-hall'].includes(l.id));
}

/** 生成版本 2 的房間池：舊版型加上新版型；入口只用新的（四面都能接門）。 */
export function layoutsByRoleV2(role: Role): RoomLayout[] {
  return LAYOUTS.filter((l) => l.role === role && !l.special && !['ember-cache', 'sentry-vault', 'guardian-hall'].includes(l.id) &&
    (role !== 'entrance' || l.v2));
}

export function layoutById(id: string): RoomLayout {
  const l = LAYOUTS.find((x) => x.id === id);
  if (!l) throw new Error(`unknown layout ${id}`);
  return l;
}
